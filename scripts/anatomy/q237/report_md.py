#!/usr/bin/env python3
"""Q237: data/derived/Q237_pairing.json (+ Q237_fill_<page>.json, Q237_after_counts.json) -> data/derived/Q237_pairing.md
    python3 scripts/anatomy/q237/report_md.py"""
from __future__ import annotations
import json, math, sys, collections
from pathlib import Path
REPO = Path(__file__).resolve().parents[3]
D = REPO / "data/derived"
J = json.loads((D / "Q237_pairing.json").read_text())
PG = J["pages"]
LAB = {k: v["label"] for k, v in PG.items()}
ORDER = ["own_m", "own_f", "comb_m", "comb_f", "base_m", "base_f"]


def cnt(units):
    c = collections.Counter(u["cls"] for u in units)
    return c, collections.Counter(u.get("kind") for u in units if u["cls"] == "unmatched")


def nstruct(u):
    return len(u.get("ids_r", [])) + len(u.get("ids_l", [])) + len(u.get("ids_m", []))


def score(u):
    m = u["metrics"]; s = 0.0
    r = m["ratio_r_over_l"]
    if r: s = max(s, abs(math.log(r)) / math.log(1.25))
    if m["iou_kind"] == "volume" and m["iou_aligned"] is not None and m["iou_aligned"] < 0.6: s = max(s, (0.6 - m["iou_aligned"]) / 0.15 + 1)
    return s


def vol(u):
    m = u["metrics"]
    return m["vol_r_cm3"] if m["vol_r_cm3"] is not None else (m["area_r_cm2"] or 0) / 10.0


L = []
w = L.append
w("# Q237 - left / right pairing and asymmetry of the six models\n")
w("Generated by `scripts/anatomy/q237/pairing.py` (classification + metrics) and `report_md.py`; machine-readable: `data/derived/Q237_pairing.json`. Reads the CURRENT pages (Q233 / Q234 / Q235 outputs), never edits them. "
  "Frame of every model: mm, +X = the subject's right. Measured data is not overwritten by a mirror image: our models are individual people and are really asymmetric.\n")
w("## 1. Midsagittal plane per model\n")
w("Fitted to the axial skeleton (ribs, sternum, vertebrae, sacrum, pelvis, shoulder girdle, skull): the plane {n.x = d} that makes the plane-reflected surface cloud of those bones most self-symmetric "
  "(75th percentile + median of the nearest-surface distance; coarse offset search then Nelder-Mead over offset / yaw / roll). Reported: the normal's tilt from the sagittal (+X) axis, the offset d at the atlas origin "
  "(= x of the plane at y = z = 0), the signed distance of the midline bones (vertebrae, sacrum, sternum, hyoid, skull base) to the plane, and the residual of the reflection.\n")
w("| model | normal n | d (mm) | tilt total / yaw / roll (deg) | reflection residual median / p95 (mm) | midline bones: median / p95 abs offset (mm), n |")
w("|---|---|---|---|---|---|")
for k in ORDER:
    p = PG[k]["plane"]; q = p["quality"]; t = p["tilt"]; mb = q["midline_bones"]
    w(f"| {LAB[k]} | ({p['n'][0]:.4f}, {p['n'][1]:.4f}, {p['n'][2]:.4f}) | {p['d_mm']:.1f} | {t['total_deg']:.2f} / {t['yaw_deg']:.2f} / {t['roll_deg']:.2f} | {q['refl_median_mm']:.2f} / {q['refl_p95_mm']:.2f} | {mb['median_offset_mm']:.1f} / {mb['p95_abs_offset_mm']:.1f}, {mb['n']} |")
w("\nThe Base models are one exactly symmetric body (plane x = 0 to 0.1 mm; the residual 1.6 mm is the sampling noise floor of the method). The own / fitted models are individuals: the offset d is measured at the origin (feet-level of the atlas frame), "
  "so it also carries the lean of the plane (roll): the plane passes through the spine, not through x = 0.\n")
w("## 2. Classification (counts per page)\n")
w("Unit = one structure group: all meshes of one anatomical name and side (pieces such as `_zfill`, re-segmented `_q212` parts and numbered vertebrae join their structure). paired = L/R twins found by naming (`_l` / `_r`, `left` / `right`, "
  "Z aliases by word overlap + mirrored position) and not lateralised; midline = crosses the plane or centroid within 12 mm; lateralised = never mirrored (liver, spleen, stomach, bowel, heart, great vessels, lungs and bronchi, "
  "carotid / subclavian / vagus / phrenic / gonadal vessels ..., single meshes far off the midline, and paired organs whose sides differ by design); unmatched = one side missing (a real gap), or one side much smaller "
  "(ratio < 0.5 or > 2), the structures the audits list as defective are in section 5.\n")
aft = {}
if (D / "Q237_after_counts.json").exists(): aft = json.loads((D / "Q237_after_counts.json").read_text())
w("| model | meshes | groups | paired | midline | lateralised | unmatched: missing side | unmatched: much smaller | paired flagged (ratio / IoU) | of which major | twin pairs (paired + much smaller) before -> after the Q237 fill |")
w("|---|---|---|---|---|---|---|---|---|---|---|")
for k in ORDER:
    us = PG[k]["units"]; c, ck = cnt(us)
    fl = [u for u in us if u.get("flags") and u["cls"] == "paired"]; mj = [u for u in fl if u.get("tier") == "major"]
    w(f"| {LAB[k]} | {PG[k]['n_structures']} | {PG[k]['n_groups']} | {c['paired']} | {c['midline']} | {c['lateralised']} | {ck['missing_side']} | {ck['much_smaller']} | {len(fl)} | {len(mj)} | {c['paired'] + ck['much_smaller']} -> {aft.get(k, {}).get('paired', '')} |")
w("\n(Paired pairs are counted as twins; one pair = two sides. 'flagged' = ratio R/L < 0.8 or > 1.25, or IoU < 0.6 after mirroring and rigid alignment (volume IoU), as the owner asked. 'major' = ratio < 0.67 or > 1.5 or aligned IoU < 0.3.)\n")
w("## 3. How the asymmetry is measured\n")
w("For every matched pair the LEFT group is reflected about the model's midsagittal plane (winding reversed) and compared with the RIGHT group: volume ratio R/L (exact for closed meshes; for open / non-manifold meshes the "
  "voxel solid of the sealed surface, 'volume (voxel)'; area ratio only when the surface encloses nothing), centroid offset after mirroring (position / posture), median symmetric surface distance (msd) and 95th-percentile "
  "Hausdorff (hd95) from 2,000 area-weighted samples per side, then a rigid ICP of the mirrored left onto the right (translation, rotation, residual msd / hd95 after alignment) and the overlap IoU of the voxel solids "
  "(common grid, pitch about extent / 70, 0.8-3 mm), both right after the plane mirroring and after the rigid alignment. The flags use the aligned IoU (a posed limb is not a shape difference); the raw mirrored IoU and the "
  "centroid offset show the posture asymmetry (limbs lie differently in these bodies: offsets of 40-100 mm are posture). Skin and fascia are sheets: area ratio and a shell IoU (no solid, never IoU-flagged); "
  "structures thinner than 4 mm (mean thickness 2V/A: nerves, small vessels, fine ligaments) keep their IoU in the table but are not flagged by it (a 1 mm misalignment of a 2 mm tube is IoU 0.3, not a shape difference); "
  "their ratio is still flagged.\n")
w("## 4. Asymmetry tables (severity x log10(1 + volume), structures >= 2 cm3; known real asymmetries are expected: dominant arm, his thumb ray, her left forearm, left elbow ...)\n")
for k in ORDER:
    us = [u for u in PG[k]["units"] if "metrics" in u and u["cls"] in ("paired", "unmatched") and u.get("tier") in ("major", "flag") and vol(u) >= 2.0]
    us.sort(key=lambda u: -score(u) * math.log10(1 + vol(u)))      # severity weighted by size: a thin tube's IoU is dominated by a 1 mm misalignment
    n = 40 if k.startswith("own") or k.startswith("comb") else 25
    w(f"### {LAB[k]}  ({len([u for u in PG[k]['units'] if u.get('tier') == 'major'])} major, {len([u for u in PG[k]['units'] if u.get('tier') == 'flag'])} flagged; top {min(n, len(us))} shown, all rows are in the JSON)\n")
    w("| structure | sys | vol R / L (cm3) | ratio R/L | centroid offset (mm) | msd mirrored / aligned (mm) | hd95 aligned | IoU mirrored / aligned | sources R / L | flags |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for u in us[:n]:
        m = u["metrics"]
        src = ("/".join(u.get("class_r", [])) + " | " + "/".join(u.get("class_l", []))) if "class_r" in u else "Z model"
        w(f"| {u['canon']} | {u['sys']} | {m['vol_r_cm3'] if m['vol_r_cm3'] is not None else '(' + str(m['area_r_cm2']) + ' cm2)'} / {m['vol_l_cm3'] if m['vol_l_cm3'] is not None else '(' + str(m['area_l_cm2']) + ' cm2)'} | {m['ratio_r_over_l']} | {m['centroid_offset_mm']} | {m['msd_mm']} / {m['msd_aligned_mm']} | {m['hd95_aligned_mm']} | {m['iou_mirror']} / {m['iou_aligned']} | {src} | {'; '.join(u['flags'])}{(' ; posed differently ' + str(u['posed_differently_mm']) + ' mm') if u.get('posed_differently_mm') else ''} |")
    w("")
w("## 5. Unmatched structures (one side missing / much smaller)\n")
for k in ORDER:
    us = [u for u in PG[k]["units"] if u["cls"] == "unmatched"]
    ms = sorted(f"{u['canon']} ({u['sys']}; only {'right' if u['only_side'] == 'r' else 'left'}" + (", " + "/".join(u.get('class_' + u['only_side'], [])) if 'class_' + u['only_side'] in u else "") + ")" for u in us if u.get("kind") == "missing_side")
    sm = sorted(f"{u['canon']} ({u['sys']}; {u['why'].split(': ')[-1]})" for u in us if u.get("kind") == "much_smaller")
    w(f"### {LAB[k]}\n")
    w(f"- one side missing ({len(ms)}): " + ("; ".join(ms) or "none"))
    w(f"- one side much smaller ({len(sm)}): " + ("; ".join(sm) or "none") + "\n")
w("## 6. Lateralised by nature and midline (not mirrored)\n")
base_lat = {u["canon"] for u in PG["base_m"]["units"] if u["cls"] == "lateralised"}
for k in ORDER:
    us = PG[k]["units"]
    lat = sorted({u["canon"] for u in us if u["cls"] == "lateralised"})
    why = collections.Counter(u["why"].split(": ")[-1][:60] for u in us if u["cls"] == "lateralised")
    w(f"- **{LAB[k]}**: {len(lat)} lateralised groups ({'; '.join(f'{a} x{b}' for a, b in why.most_common(8))}); {len([u for u in us if u['cls'] == 'midline'])} midline groups.")
    if k in ("own_m", "own_f", "base_m"):
        w("  - lateralised: " + ", ".join(lat))
        w("  - midline: " + ", ".join(sorted({u["canon"] for u in us if u["cls"] == "midline"})))
    else:
        w("  - lateralised, differing from Base male: " + ("+ " + ", ".join(sorted(set(lat) - base_lat)) if set(lat) - base_lat else "none added") + "; " + ("- " + ", ".join(sorted(base_lat - set(lat))) if base_lat - set(lat) else "none missing"))
w("")
w("Full lists (every structure with its class and reason) are in `data/derived/Q237_pairing.json` (`pages.<key>.units`).\n")
w("## 7. Fill (step 3) and recommendations\n")
for k in ORDER:
    f = D / f"Q237_fill_{k}.json"
    if not f.exists(): continue
    d = json.loads(f.read_text()); st = d["structures"]
    w(f"### {LAB[k]}\n")
    sh = [r for r in st if r["decision"] == "shipped"]; hd = [r for r in st if r["decision"] == "held"]; rc = [r for r in st if r["decision"] == "recommendation"]
    w(f"- shipped ({len(sh)}): " + ("; ".join(f"{r['canon']} [{r['kind']}: {r['source_side']}->{r['target_side']}, fit {r['fit']['bone_residual_median_mm']} / {r['fit']['bone_residual_p90_mm']} mm (median / p90), scale {r['fit']['scale']}, {(str(r['volume_new_cm3']) + ' cm3') if r.get('volume_new_cm3') is not None else (str(r['area_new_cm2']) + ' cm2 sheet')}]" for r in sh) or "none"))
    w(f"- held ({len(hd)}): " + ("; ".join(f"{r['canon']} ({(r.get('reasons') or [''])[0][:110]})" for r in hd) or "none"))
    w(f"- recommendations only ({len(rc)}): " + ("; ".join(f"{r['canon']} ({r['kind']}, {r['source_side']}->{r['target_side']})" for r in rc) or "none") + "\n")
w("## 8. Known real asymmetries found again in the table\n")
w("The audits and notes of Q198 / Q224 / Q225 list real or modelling asymmetries; the measurements above see them (rows below are the same numbers as section 4 / the JSON). They are NOT filled or mirrored: they are measured / documented data, or recommendations.\n")
KNOWN = {"own_m": ("his thumb ray (metacarpals, adductor / abductor pollicis, extensor pollicis brevis)", ["metacarpals", "adductor_pollicis", "abductor_pollicis_longus", "extensor_pollicis_brevis", "phalanges_hand"]),
         "own_f": ("her left forearm / hand and left wrist (Z-filled left, measured right), piriformis left, carpal ligaments", ["carpals", "phalanges_hand", "extensor_carpi_ulnaris", "flexor_carpi_ulnaris", "piriformis", "brachioradialis", "extensor_digitorum"]),
         "comb_f": ("her left forearm muscles of the Combined page (ends off their bones, overlap), left elbow", ["flexor_carpi_ulnaris", "extensor_digitorum", "flexor_digitorum_superficialis", "anconeus", "supinator", "humerus", "ulna", "radius"])}
for k, (what, names) in KNOWN.items():
    w(f"### {LAB[k]}: {what}\n")
    w("| structure | vol R / L (cm3) | ratio R/L | IoU aligned | centroid offset (mm) | class |")
    w("|---|---|---|---|---|---|")
    for u in PG[k]["units"]:
        if "metrics" in u and u["canon"] in names:
            m = u["metrics"]
            w(f"| {u['canon']} ({u['sys']}) | {m['vol_r_cm3']} / {m['vol_l_cm3']} | {m['ratio_r_over_l']} | {m['iou_aligned']} | {m['centroid_offset_mm']} | {u['cls']}{(' / ' + u.get('kind', '')) if u.get('kind') else ''} |")
    w("")
(D / "Q237_pairing.md").write_text("\n".join(L) + "\n")
print("wrote", D / "Q237_pairing.md", len("\n".join(L)))
