#!/usr/bin/env python3
"""Q297 provenance audit: classify EVERY shipped mesh of the six pages into
    a  measured   -- segmented from THIS subject's own imaging (CT / cryosections)
    b  real_third_party -- a real mesh of a real body from another source, registered onto this page
                           (Z-Anatomy / BodyParts3D, HuBMAP HRA donor organs, Chinese Visible Human, SPL Open Anatomy,
                            the other Visible Human, another TotalSegmentator specimen, a mirror of this body's own side)
    c  rule_based -- geometry generated by a documented rule, with a citation behind the rule
    d  unaccounted -- geometry whose shape cannot be traced to any real source OR to a stated rule with a citation

and, separately, whether the page actually SHOWS that: a structure can be rule-based in the data and still print
"Measured on this body" on its card, which is the thing this round was asked to find.

    python3 scripts/anatomy/q297/audit297.py [--src BUILD_DIR] [--json OUT]   (default: the current baseline)"""
from __future__ import annotations
import json, re, sys, collections
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(HERE))
import prov297 as P  # noqa: E402

OUT = REPO / "data/derived/Q297_provenance_audit.json"

# --- the words a badge / source / subject uses for each real source we hold (all of them already in the repo) ---
THIRD_PARTY = [
    (r"Z-Anatomy|BodyParts3D|zan_|Z-Anatomy fill|FILLED from Z-Anatomy", "Z-Anatomy / BodyParts3D (CC BY-SA)"),
    (r"HuBMAP|Human Reference Atlas|HRA", "HuBMAP Human Reference Atlas (CC BY 4.0)"),
    (r"Chinese Visible Human|CVH|Wu et al", "Chinese Visible Human female, Wu et al. 2015 (CC BY 4.0)"),
    (r"Open Anatomy|SPL|Brigham", "SPL / Open Anatomy (3D Slicer License Part B)"),
    (r"s1159", "another TotalSegmentator specimen (s1159)"),
    (r"MIRROR IMAGE|mirror_", "mirror of this body's own opposite side"),
    # NB: matched on the TRANSFER subject id only. The plain words "Visible Human female" appear in almost every card on
    # these pages (she IS the Visible Human female), so matching them as text would file her own CT as a third party.
    (r"xfer_vhm2vhf|xfer_vhf2vhm|TRANSFERRED, re-bounded|Transferred from the other Visible Human", "the other Visible Human body"),
]
MEASURED = r"(MEASURED FROM IMAGING|measured on this body|segmented (on|from) (her|his) own|HER OWN|HIS OWN|TotalSegmentator|cryosection|Traced in (his|her) own|re-segmented from (his|her))"
RULE = r"(RULE-BASED|PROCEDURAL/RULE-BASED|rule-based|Rule-based|SURFACE CLOSURE|gap closure|hole fill|minimal surface|shape interpolation|bone carve|Rule-based bridge)"
CITED = r"(Gray's|Moore|doi:|PMID|et al\.|Atlas of Anatomy|Terminologia|Standring|Netter|Drake|Clinically Oriented Anatomy|cadaveric)"
# geometry this project GENERATED outright -- not a real mesh adjusted by a rule (that is "Q162 gap closure", which keeps
# the Z mesh's own shape to within ~1 mm), but a surface invented to span a hole. Checked before anything else, because
# such a badge usually also NAMES a real source while explaining what is missing from it.
GENERATED_HERE = r"(SURFACE CLOSURE, NOT ANATOMY|Pinkall-Polthier|rule-based hole fill|discrete minimal surface)"


def blob(st):
    r = st["rec"]
    return " || ".join(str(r.get(k) or "") for k in ("procedural_badge", "source", "geom_src", "notes", "method")) + " || " + st["subject"]


def classify(st, page_kind, L=None):
    """-> (class, source_name, why).

    Ground truth is taken from the thing the build pipeline actually controls -- the structure's SUBJECT id, which this
    project names by convention (`ct_vhf_*` / `vhm_*` = that body's own imaging; `rule_*` / `*_rule_*` = built by a rule;
    `xfer_*` / `mirror_*` / `ct_s1159*` = a real mesh from elsewhere registered on) -- and only then refined by the
    card's own badge / source text. It is deliberately NOT taken from SUBJECT_LABELS, because an absent or wrong label is
    exactly the defect this round is looking for."""
    L = L or {}
    r = st["rec"]
    badge = r.get("procedural_badge") or ""
    sub = st["subject"] or ""
    t = blob(st)
    cited = bool(re.search(CITED, t))

    def rule(src_txt):
        return ("c_rule_based", src_txt, "rule-generated shape with a citation") if cited else \
               ("d_unaccounted", "none", "rule-generated shape with no citation recorded for it")

    # 0. a surface this project generated to span a hole: real only if a cited rule fixes its shape
    if re.search(GENERATED_HERE, badge):
        return ("c_rule_based", "generated surface, cited rule", "generated hole fill with a citation") if cited else \
               ("d_unaccounted", "none", "a surface generated here to span a hole: no anatomical source and no citation for its shape")
    # 1. built by a rule -- by subject id, by method, or because the badge OPENS with rule wording
    if re.search(r"(^|_)rule(_|$)|rule_nerve|rule_rf|rule_pfc", sub) \
       or re.match(r"\s*rule-based", str(r.get("method") or ""), re.I) \
       or re.match(r"\s*(" + RULE + r")", badge):
        return rule("documented rule")
    # 2. a real mesh from another source, registered onto this page
    for pat, name in (("^mirror_", "mirror of this body's own opposite side"),
                      ("^xfer_hrasculpt2", "HuBMAP HRA reference model (sculpted by its authors, CC BY 4.0)"),
                      ("^xfer_hra2", "HuBMAP Human Reference Atlas, same donor (CC BY 4.0)"),
                      ("^xfer_cvh2", "Chinese Visible Human female, Wu et al. 2015 (CC BY 4.0)"),
                      ("^xfer_zan2", "Z-Anatomy / BodyParts3D (CC BY-SA)"),
                      ("^ct_s1159", "another TotalSegmentator specimen (s1159)"),
                      ("^xfer_", "the other Visible Human body")):
        if re.search(pat, sub):
            return "b_real_third_party", name, "subject id names a registered third-party / transferred mesh"
    # 3. this body's own imaging
    if re.match(r"(ct_|cryo_)?(vhm|vhf)[_0-9]*$|^ct_vh[mf]_|^vh[mf]_|^img_vh[mf]_", sub):
        return "a_measured", "this subject's own imaging", "subject id names this body's own CT / cryosection task"
    # 4. the Z pages: the record decides, else the page-level Z-Anatomy attribution
    if page_kind == "zan":
        for pat, name in THIRD_PARTY:
            if re.search(pat, (badge + " " + str(r.get("source") or "") + " " + str(r.get("geom_src") or ""))):
                return "b_real_third_party", name, "the card names a real third-party source"
        if re.search(MEASURED, t):
            return "a_measured", "this subject's own imaging", "the card says segmented from this body's own imaging"
        if re.search(RULE, t):
            return rule("documented rule (stated later in the record)")
        return "b_real_third_party", "Z-Anatomy / BodyParts3D (CC BY-SA), page-level attribution", \
               "plain Z-Anatomy mesh: provenance is the page manifest attribution"
    # 5. own pages, unknown subject: fall back to the card text
    for pat, name in THIRD_PARTY:
        if re.search(pat, t):
            return "b_real_third_party", name, "the card names a real third-party source"
    if re.search(MEASURED, t):
        return "a_measured", "this subject's own imaging", "the card says segmented from this body's own imaging"
    if re.search(RULE, t):
        return rule("documented rule (stated later in the record)")
    return "d_unaccounted", "none", "no badge, no source and no recognised subject id"



# Q308: the baseline is ASKED FOR, never written down here. `scripts/anatomy/q241/model.SRC` is the one place
# in this repository that declares which build the six pages come from, and `model.build_root()` reads it. A
# second copy of the literal goes stale silently the moment a round lands -- which is exactly what happened to
# this module: its default stayed `build/q296`, where the provenance audit reports d_unaccounted = 2, so every
# run without an explicit --src kept auditing the PRE-Q297 state and reporting it as today's.
def _baseline():
    import sys as _s
    _p = str(REPO / "scripts/anatomy/q241")
    if _p not in _s.path:
        _s.path.insert(0, _p)
    import model as _m
    return _m.build_root()


def run(src=None):
    src = src or _baseline()   # Q308: the current baseline, not a stale literal
    rep = {"src": src, "pages": {}, "class_totals": collections.Counter(),
           "mislabelled": [], "rule_without_visible_badge": [], "unaccounted": []}
    for key in P.KEYS:
        h, d, kind = P.page_html(key, src)
        L = P.subject_labels(h) if kind == "own" else {}
        S = P.structures(key, src)
        cnt = collections.Counter(); rows = []
        for st in S:
            cls, srcname, why = classify(st, kind, L)
            cnt[cls] += 1
            rep["class_totals"][cls] += 1
            badge = st["rec"].get("procedural_badge") or ""
            shown = P.classify_source(st["subject"], badge, L) if kind == "own" else None
            row = dict(id=st["id"], page=key, sys=st["sys"], cls=cls, source=srcname, why=why,
                       badge=bool(badge), hd=st["hd"], shown_class=shown)
            rows.append(row)
            # the page claims "measured" for geometry that is not measured
            if kind == "own" and shown == "measured" and cls in ("c_rule_based", "d_unaccounted"):
                rep["mislabelled"].append(dict(row, claim="card prints 'Measured on this body'"))
            # rule-based with nothing rule-shaped visible on the card
            if cls == "c_rule_based":
                visible = bool(re.search(RULE, badge)) or (kind == "own" and shown == "rule_based")
                if not visible:
                    rep["rule_without_visible_badge"].append(row)
            if cls == "d_unaccounted":
                rep["unaccounted"].append(row)
        rep["pages"][key] = {"label": P.LABEL[key], "kind": kind, "meshes": len(S), "classes": dict(cnt)}
    rep["class_totals"] = dict(rep["class_totals"])
    return rep


def main(argv):
    src = _baseline()
    if "--src" in argv:
        src = argv[argv.index("--src") + 1]
    out = Path(argv[argv.index("--json") + 1]) if "--json" in argv else OUT
    rep = run(src)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(rep, indent=1), encoding="utf-8")
    print("src", src)
    for k, v in rep["pages"].items():
        print(f"  {v['label']:12s} {v['meshes']:5d}  " + "  ".join(f"{c}={n}" for c, n in sorted(v["classes"].items())))
    print("TOTALS", rep["class_totals"])
    print("cards that claim 'measured' for geometry that is not measured:", len(rep["mislabelled"]))
    for r in rep["mislabelled"][:4]:
        print("   ", r["page"], r["id"], r["cls"])
    print("rule-based with no rule wording visible on the card:", len(rep["rule_without_visible_badge"]))
    for r in rep["rule_without_visible_badge"][:6]:
        print("   ", r["page"], r["id"])
    print("class (d) unaccounted:", len(rep["unaccounted"]))
    for r in rep["unaccounted"][:12]:
        print("   ", r["page"], r["id"], "|", r["why"])
    print("written", out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
